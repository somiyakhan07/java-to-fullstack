// Check Odd Even

public class CheckOddEven{
    public static void main(String[] args){
        int num = 14;

        if(num%2 == 0){
            System.out.println(num + " is a even number");
        }
        else{
            System.out.println(num + " is a odd number");
        }
    }
}
// 14 is a even number