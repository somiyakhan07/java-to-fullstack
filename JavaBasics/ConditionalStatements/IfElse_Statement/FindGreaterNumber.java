// Find greater number

public class FindGreaterNumber {
    public static void main(String[] args){
        int num1 = 21;
        int num2 = 43;

        if(num1 > num2){
            System.out.println("num1: " + num1 + " is greater");
        }
        else{
            System.out.println("num2: " + num2 + " is greater");
        }

    }
    
}
// num2: 43 is greater
