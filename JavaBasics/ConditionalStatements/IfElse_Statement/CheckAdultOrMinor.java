// Check Adult or Minor

public class CheckAdultOrMinor {
    public static void main(String[] args) {
        String name = "Sanam";
        int age = 21;

        if (age >= 18) {
            System.out.println(name + " is an adult");
            System.out.println("Age: " + age);
        } else {
            System.out.println(name + " is an minor");
            System.out.println("Age: " + age);
        }
    }
}
// Sanam is an adult
// Age: 21
